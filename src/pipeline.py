"""Run the whole project with one command:  python -m src.pipeline

Stages
  3  Data understanding  - count images per defect type, check masks
  6  Modeling            - PatchCore memory bank from GOOD images only; global-kNN baseline
  7  Evaluation          - AUROC (threshold-free), cost-based threshold on the
                           calibration half, honest results on the evaluation half
  8  Explainability      - heatmaps: WHERE the model sees the defect
  9  Edge deployment     - ONNX export + latency benchmark
 10  Reporting           - reports/results.md and the results block in README.md
Everything written into the results files comes from this run - nothing is typed by hand.
"""
import json
import os
import re
import time

import numpy as np
import pandas as pd
import torch

from src import plotting
from src.config import (CALIBRATION_SHARE, CATEGORY, CORESET_RATIO, COST_FALSE_REJECT,
                        COST_MISSED_DEFECT, IMAGE_SIZE, MODELS_DIR, REPORTS_DIR, ROOT,
                        SMOKE_TEST, ensure_dirs)
from src.data import (list_images, load_display_image, load_mask,
                      split_calibration_evaluation)
from src.edge import benchmark, export_onnx
from src.evaluation import (best_threshold, cost_curve, decisions_summary, image_auroc,
                            pixel_auroc)
from src.patchcore import GlobalKNNBaseline, PatchCore


def log(msg=""):
    print(msg, flush=True)


def data_overview(df):
    test = df[df["split"] == "test"]
    counts = test.groupby("defect_type").size().rename("test_images").to_frame()
    counts["masks_found"] = test.groupby("defect_type")["mask_path"].apply(lambda s: s.notna().sum())
    return {
        "train_good": int((df["split"] == "train").sum()),
        "test_good": int(((df["split"] == "test") & (df["label"] == 0)).sum()),
        "test_defective": int(((df["split"] == "test") & (df["label"] == 1)).sum()),
        "per_type": counts.reset_index().to_dict(orient="records"),
    }


def detection_by_type(frame, threshold):
    defects = frame[frame["label"] == 1].copy()
    defects["caught"] = defects["score"] >= threshold
    table = defects.groupby("defect_type").agg(count=("caught", "size"), caught=("caught", "sum"))
    table["detection_rate"] = table["caught"] / table["count"]
    return table.reset_index()


def pick_examples(frame, n_per_type=1):
    """Highest-scoring defect of each type + the highest-scoring good part."""
    rows = []
    for defect, group in frame[frame["label"] == 1].groupby("defect_type"):
        rows.extend(group.nlargest(n_per_type, "score").to_dict("records"))
    rows.extend(frame[frame["label"] == 0].nlargest(1, "score").to_dict("records"))
    return rows


def write_reports(r):
    """reports/results.md + the results block in README.md, generated from numbers in r."""
    ev, cal = r["evaluation_half"], r["calibration"]
    lat = "\n".join(f"| {k} | {v:.0f} ms |" for k, v in r["latency_ms"].items())
    per_type = "\n".join(
        f"| {t['defect_type']} | {t['caught']}/{t['count']} | {t['detection_rate']:.0%} |"
        for t in r["detection_by_type"])
    md = f"""## Results: `{r['category']}` (generated by `python -m src.pipeline` on {r['run_date']})

| Metric | PatchCore | Global-kNN baseline |
|---|---|---|
| Image AUROC (full test set, threshold-free) | **{r['patchcore']['image_auroc']:.3f}** | {r['baseline']['image_auroc']:.3f} |
| Pixel AUROC (does the heatmap hit the defect?) | **{r['patchcore']['pixel_auroc']:.3f}** | not possible (no heatmap) |

**Decision threshold** chosen on the calibration half ({cal['n_images']} images) by business cost
(missed defect = {COST_MISSED_DEFECT}, good part wrongly rejected = {COST_FALSE_REJECT}).

**Evaluation half** ({ev['n_images']} images, used once):

| | Count |
|---|---|
| Defects caught | **{ev['defects_caught']} of {ev['defects_caught'] + ev['defects_missed']}** ({ev['defect_detection_rate']:.1%}) |
| Defects missed | {ev['defects_missed']} |
| Good parts wrongly rejected | {ev['good_rejected']} of {ev['good_rejected'] + ev['good_passed']} ({ev['false_reject_rate']:.1%}) |
| Business cost | {ev['business_cost']} |

| Defect type | Caught | Detection rate |
|---|---|---|
{per_type}

**Speed per image** (feature extraction + nearest-neighbour search, median):

| Runtime | Latency |
|---|---|
{lat}

ONNX export check: largest difference to PyTorch features = {r['onnx_max_diff']:.2e}.
Memory bank: {r['memory_bank_size']:,} patches from {r['data']['train_good']} good training images.
"""
    if r["smoke_test"]:
        md = "> **SMOKE TEST on synthetic images with random weights - not real results.**\n\n" + md
    (REPORTS_DIR / "results.md").write_text(md, encoding="utf-8")

    readme = ROOT / "README.md"
    if readme.exists():
        text = readme.read_text(encoding="utf-8")
        text = re.sub(r"<!-- RESULTS:START -->.*<!-- RESULTS:END -->",
                      "<!-- RESULTS:START -->\n" + md + "<!-- RESULTS:END -->",
                      text, flags=re.S)
        readme.write_text(text, encoding="utf-8")


def main():
    ensure_dirs()
    plotting.set_style()
    t0 = time.time()
    device = "cuda" if torch.cuda.is_available() else "cpu"
    log(f"Category: {CATEGORY} | device: {device}"
        + (f" ({torch.cuda.get_device_name(0)})" if device == "cuda" else ""))

    # ---- Stage 3: data -------------------------------------------------------
    df = list_images(CATEGORY)
    overview = data_overview(df)
    log(f"Train (good only): {overview['train_good']} | test good: {overview['test_good']} "
        f"| test defective: {overview['test_defective']}")
    train = df[df["split"] == "train"]
    test = df[df["split"] == "test"].reset_index(drop=True)

    # ---- Stage 6: models -----------------------------------------------------
    log("\nFitting PatchCore on good images only...")
    model = PatchCore().fit(train["path"].tolist(), log=log)
    model.save(MODELS_DIR / f"patchcore_{CATEGORY}.pt")
    log("Fitting global-kNN baseline...")
    baseline = GlobalKNNBaseline(model).fit(train["path"].tolist())

    log("Scoring the test set...")
    maps, scores = model.predict(test["path"].tolist())
    test["score"] = scores
    test["baseline_score"] = baseline.predict(test["path"].tolist())
    masks = np.stack([load_mask(p) for p in test["mask_path"]])

    # ---- Stage 7: evaluation -------------------------------------------------
    pc_auc = image_auroc(test["label"], test["score"])
    bl_auc = image_auroc(test["label"], test["baseline_score"])
    px_auc = pixel_auroc(masks, maps)
    log(f"\nImage AUROC  PatchCore {pc_auc:.3f} | baseline {bl_auc:.3f}")
    log(f"Pixel AUROC  PatchCore {px_auc:.3f}")

    calib, evaluation = split_calibration_evaluation(test)
    threshold, calib_cost = best_threshold(calib["label"], calib["score"])
    ev = decisions_summary(evaluation["label"], evaluation["score"], threshold)
    ev["n_images"] = int(len(evaluation))
    by_type = detection_by_type(evaluation, threshold)
    log(f"Threshold {threshold:.3f} (calibration cost {calib_cost}) -> evaluation half: "
        f"caught {ev['defects_caught']}/{ev['defects_caught'] + ev['defects_missed']} defects, "
        f"{ev['good_rejected']} good parts rejected")

    # ---- Figures ------------------------------------------------------------
    plotting.plot_score_distribution(evaluation["score"], evaluation["label"], threshold,
                                     "Anomaly scores on the evaluation half", "score_distribution.png")
    plotting.plot_roc(test["label"], [("PatchCore", test["score"], pc_auc),
                                      ("Global-kNN baseline", test["baseline_score"], bl_auc)],
                      "roc_curves.png")
    t_grid, c_grid = cost_curve(calib["label"], calib["score"])
    plotting.plot_cost_curve(t_grid, c_grid, threshold, "cost_vs_threshold.png")
    plotting.plot_detection_by_type(by_type, "detection_by_type.png")

    # ---- Stage 8: heatmaps ---------------------------------------------------
    vmin, vmax = np.percentile(maps, 1), np.percentile(maps, 99.9)
    index = {p: i for i, p in enumerate(test["path"])}

    def examples(rows, title, name):
        idx = [index[r["path"]] for r in rows]
        plotting.plot_examples(rows, [load_display_image(r["path"]) for r in rows],
                               [maps[i] for i in idx], [masks[i] for i in idx],
                               vmin, vmax, title, name)

    examples(pick_examples(test), "Where the AI sees each defect type", "heatmap_examples.png")
    missed = evaluation[(evaluation["label"] == 1) & (evaluation["score"] < threshold)]
    examples(missed.nlargest(6, "score").to_dict("records"),
             "Missed defects (evaluation half)", "missed_defects.png")
    rejected = evaluation[(evaluation["label"] == 0) & (evaluation["score"] >= threshold)]
    examples(rejected.nlargest(6, "score").to_dict("records"),
             "Good parts wrongly rejected (evaluation half)", "false_rejects.png")

    # ---- Stage 9: edge -------------------------------------------------------
    log("\nExporting to ONNX and benchmarking...")
    onnx_path = export_onnx(model)
    latency, max_diff = benchmark(model, onnx_path)
    for k, v in latency.items():
        log(f"  {k}: {v:.0f} ms per image")

    # ---- Save everything -----------------------------------------------------
    calib_summary = decisions_summary(calib["label"], calib["score"], threshold)
    calib_summary["n_images"] = int(len(calib))
    results = {
        "category": CATEGORY, "run_date": time.strftime("%Y-%m-%d"),
        "smoke_test": SMOKE_TEST, "device": device, "image_size": IMAGE_SIZE,
        "coreset_ratio": CORESET_RATIO, "calibration_share": CALIBRATION_SHARE,
        "costs": {"missed_defect": COST_MISSED_DEFECT, "false_reject": COST_FALSE_REJECT},
        "data": overview, "memory_bank_size": int(model.memory_bank.shape[0]),
        "patchcore": {"image_auroc": pc_auc, "pixel_auroc": px_auc},
        "baseline": {"image_auroc": bl_auc},
        "threshold": threshold, "calibration": calib_summary, "evaluation_half": ev,
        "detection_by_type": by_type.to_dict(orient="records"),
        "latency_ms": latency, "onnx_max_diff": max_diff,
        "runtime_minutes": round((time.time() - t0) / 60, 1),
    }
    (REPORTS_DIR / "results.json").write_text(json.dumps(results, indent=2, default=float))
    test.assign(set=np.where(test["path"].isin(calib["path"]), "calibration", "evaluation"),
                decision=np.where(test["score"] >= threshold, "reject", "pass")) \
        .drop(columns=["mask_path"]) \
        .assign(path=lambda d: d["path"].map(lambda p: os.path.relpath(p, ROOT).replace(os.sep, "/"))) \
        .to_csv(REPORTS_DIR / "test_scores.csv", index=False)
    write_reports(results)
    log(f"\nDone in {results['runtime_minutes']} min. See reports/results.md and reports/figures/.")


if __name__ == "__main__":
    main()
